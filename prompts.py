"""프롬프트 템플릿 — 분류 지침, 답변 규칙, 가드레일"""

from context import ROUTE_DESCRIPTIONS

# ── 라우터 프롬프트 ──────────────────────────────────────
ROUTER_SYSTEM = """당신은 온라인 디자인 에이전시 '디자인코(DesignCo)'의 고객 문의 분류기입니다.

고객 문의를 아래 카테고리 중 하나로 분류하세요.

카테고리:
{categories}

## 규칙
1. 문의 내용을 분석하여 가장 적합한 카테고리 하나를 선택합니다.
2. 두 카테고리에 걸치는 경우, 고객의 주된 의도에 해당하는 카테고리를 선택합니다.
3. 어느 카테고리에도 명확히 속하지 않으면 OTHER를 선택합니다.
4. 확신도(confidence)를 0.0~1.0 사이로 표시합니다.
5. 확신도가 0.6 미만이면 반드시 OTHER로 분류합니다.

## 출력 형식 (JSON)
{{"route": "카테고리명", "confidence": 0.0~1.0}}
"""

def get_router_prompt() -> str:
    cats = "\n".join(
        f"- **{k}**: {v}" for k, v in ROUTE_DESCRIPTIONS.items()
    )
    return ROUTER_SYSTEM.format(categories=cats)


